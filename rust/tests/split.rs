#[test]
fn enum_schema_holds_the_values() {
    let tmp = Tmp::new();
    enum_schema(&tmp, "Kind", vec![
        ev("A", V::E, V::from("첫째")), ev("B", V::from(5), V::from("둘째")), ev("C", V::E, V::E),
    ]);
    schema(&tmp, "Items", &[("Id", "ID<int32>", "all"), ("Kind", "EKind", "all")]);
    data(&tmp.join("Data.xlsx"), vec![("Items", sheet(row!["Id", "Kind"], vec![row![1, "B"]]))]);
    let out = tmp.join("out");
    assert_eq!(build(&tmp, &out, &[]).code, 0);
    let header = read(&out.join("cpp/EDrKind.h"));
    assert!(header.starts_with("// Generated by DrTableSystem. Do not edit. Source: Enums/Kind.enum.xlsx / Kind\n"));
    for part in ["A = 0", "B = 5", "C = 6", "둘째"] {
        assert!(header.contains(part), "{part}");
    }
}

#[test]
fn enum_schema_validation() {
    let cases = [
        (vec![ev("Bad-Name", V::E, V::E)], "A2", "올바르지 않은 열거자 이름"),
        (vec![ev("A", V::E, V::E), ev("A", V::E, V::E)], "A3", "중복"),
        (vec![ev("A", V::from("x"), V::E)], "B2", "정수가 아닙니다"),
        (vec![ev("A", V::from(300), V::E)], "B2", "uint8"),
        (vec![ev("A", V::from(1), V::E), ev("B", V::from(1), V::E)], "B3", "열거형 값 1가 중복"),
    ];
    for (values, cell, message) in cases {
        let tmp = Tmp::new();
        enum_schema(&tmp, "Kind", values);
        memo(&tmp.join("Data.xlsx"));
        let result = build(&tmp, &tmp.join("out"), &[]);
        assert_eq!(result.code, 1, "{message}");
        assert!(result.stderr.contains(&format!("[Enums/Kind.enum.xlsx]Kind!{cell}")), "{}", result.stderr);
        assert!(result.stderr.contains(message), "{}", result.stderr);
    }
}

