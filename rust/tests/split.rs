//! Schema files bound to data sheets, split tables, and the [File]Sheet location form.
//!
//! These tests write the schema files themselves and save data workbooks plainly.

#[macro_use]
mod common;

use common::*;
use serde_json::json;
use std::fs;
use std::path::Path;

const FIELDS: [(&str, &str, &str); 3] = [("Id", "ID<int32>", "all"), ("Name", "name", "all"), ("Cost", "int32", "server")];

fn names_row() -> Row {
    row!["Id", "Name", "Cost"]
}

/// Rows 2-3 of a data sheet show the schema; the build does not read them.
fn view() -> [Row; 2] {
    [vec![V::from("(보기)"); 3], vec![V::from("(보기)"); 3]]
}

/// A data sheet: header, the two view rows, then data.
fn sheet(header: Row, data: Vec<Row>) -> Vec<Row> {
    let mut rows = vec![header];
    rows.extend(view());
    rows.extend(data);
    rows
}

fn schema(folder: &Path, name: &str, items: &[(&str, &str, &str)]) {
    write_schema(&folder.join(format!("{name}.schema.xlsx")), name, &fields(items));
}

/// An enum schema in folder/Enums.
fn enum_schema(folder: &Path, name: &str, values: Vec<(V, V, V)>) {
    write_enum(&folder.join("Enums").join(format!("{name}.enum.xlsx")), name, &values);
}

fn data(path: &Path, sheets: Vec<(&str, Vec<Row>)>) {
    let mut book = Book::new();
    for (name, rows) in sheets {
        book.add(name, rows);
    }
    book.save_plain(path);
}

fn memo(path: &Path) {
    data(path, vec![("#메모", vec![row!["x"]])]);
}

fn rows(root: &Path, scope: &str, table: &str) -> serde_json::Value {
    json(&root.join(scope).join(format!("{table}.json")))["rows"].clone()
}

fn ids(root: &Path, scope: &str, table: &str) -> Vec<i64> {
    rows(root, scope, table).as_array().unwrap().iter().map(|row| row["Id"].as_i64().unwrap()).collect()
}

fn ev(name: &str, value: V, comment: V) -> (V, V, V) {
    (V::from(name), value, comment)
}

#[test]
fn same_sheet_name_in_several_files_is_one_table() {
    let tmp = Tmp::new();
    let folder = tmp.join("data");
    schema(&folder, "Items", &FIELDS);
    data(&folder.join("Items.xlsx"), vec![
        ("Items#무기", sheet(names_row(), vec![row![1, "Sword", 10]])),
        ("Items #방어구", sheet(names_row(), vec![row![20, "Mail", 30]])),
        ("#메모", vec![row!["아무거나"]]),
    ]);
    // Files in subfolders join too, and the column order is free.
    data(&folder.join("event/Summer.xlsx"), vec![("Items#여름", sheet(row!["Cost", "Id", "Name"], vec![row![5, 3, "Fan"]]))]);
    let out = tmp.join("out");
    assert_eq!(build(&folder, &out, &[]).code, 0);
    let server = rows(&out, "server", "Items");
    assert_eq!(server, json!([
        {"Id": 1, "Name": "Sword", "Cost": 10},
        {"Id": 3, "Name": "Fan", "Cost": 5},
        {"Id": 20, "Name": "Mail", "Cost": 30},
    ]));
    let order: Vec<&String> = server[1].as_object().unwrap().keys().collect();
    assert_eq!(order, ["Id", "Name", "Cost"]);
    // The code names only the schema file; the data places are in the manifest.
    assert!(read(&out.join("cpp/DrItemsRow.h"))
        .starts_with("// Generated by DrTableSystem. Do not edit. Source: Items.schema.xlsx\n"));
    let manifest = json(&out.join("client/manifest.json"));
    let entry = manifest["tables"].as_array().unwrap().iter().find(|item| item["name"] == "Items").unwrap();
    assert_eq!(entry["schema"], "Items.schema.xlsx");
    assert_eq!(entry["sources"], json!([
        {"file": "Items.xlsx", "sheet": "Items#무기", "rows": 1},
        {"file": "Items.xlsx", "sheet": "Items #방어구", "rows": 1},
        {"file": "event/Summer.xlsx", "sheet": "Items#여름", "rows": 1},
    ]));
}

#[test]
fn split_table_matches_unsplit_output() {
    let tmp = Tmp::new();
    for folder in ["one", "split"] {
        schema(&tmp.join(folder), "Items", &FIELDS);
    }
    data(&tmp.join("one/Items.xlsx"), vec![("Items", sheet(names_row(), vec![row![1, "Sword", 10], row![2, "Axe", 12]]))]);
    data(&tmp.join("split/a.xlsx"), vec![("Items", sheet(names_row(), vec![row![2, "Axe", 12]]))]);
    data(&tmp.join("split/b.xlsx"), vec![("Items", sheet(names_row(), vec![row![1, "Sword", 10]]))]);
    assert_eq!(build(&tmp.join("one"), &tmp.join("o1"), &[]).code, 0);
    assert_eq!(build(&tmp.join("split"), &tmp.join("o2"), &[]).code, 0);
    for scope in ["client", "server"] {
        let file = format!("{scope}/Items.json");
        assert_eq!(fs::read(tmp.join("o1").join(&file)).unwrap(), fs::read(tmp.join("o2").join(&file)).unwrap());
    }
}

#[test]
fn data_edits_never_change_generated_code() {
    let tmp = Tmp::new();
    let folder = tmp.join("data");
    schema(&folder, "Items", &FIELDS);
    let mut outputs = Vec::new();
    for (run, data_rows) in [("a", vec![row![1, "Sword", 10]]), ("b", vec![row![1, "Axe", 99], row![2, "Bow", 5]])] {
        let mut sheet_rows = vec![names_row(), vec![V::from("바뀐 보기"); 3], vec![]];
        sheet_rows.extend(data_rows);
        data(&folder.join("Items.xlsx"), vec![("Items", sheet_rows)]);
        let out = tmp.join(run);
        assert_eq!(build(&folder, &out, &[]).code, 0);
        outputs.push(files(&out.join("cpp")));
    }
    assert_eq!(outputs[0], outputs[1]);
}

