#[test]
fn workbooks_saved_without_dimensions() {
    // Files saved by streaming writers carry no sheet size (<dimension>).
    let tmp = Tmp::new();
    schema(&tmp, "Items", &FIELDS);
    let path = tmp.join("Items.xlsx");
    data(&path, vec![("Items", vec![names_row(), vec![], vec![], row![1, "Sword", 10], row![2, "Axe", 12]])]);
    let mut removed = false;
    rewrite_zip(&path, |name, bytes| {
        if !name.starts_with("xl/worksheets/") {
            return bytes;
        }
        let text = String::from_utf8(bytes).unwrap();
        let start = text.find("<dimension").expect("dimension");
        let end = start + text[start..].find("/>").unwrap() + 2;
        removed = true;
        format!("{}{}", &text[..start], &text[end..]).into_bytes()
    });
    assert!(removed);
    let out = tmp.join("out");
    assert_eq!(build(&tmp, &out, &[]).code, 0);
    assert_eq!(ids(&out, "server", "Items"), [1, 2]);
}

#[test]
fn enum_folder_sits_next_to_the_schema_folder() {
    let tmp = Tmp::new();
    let table = tmp.join("Table");
    schema(&table.join("Schema"), "Items", &[("Id", "ID<int32>", "all"), ("Kind", "EKind", "all")]);
    enum_schema(&table, "Kind", vec![ev("A", V::E, V::E), ev("B", V::E, V::E)]); // Table/Enums
    data(&table.join("Items.xlsx"), vec![("Items", sheet(row!["Id", "Kind"], vec![row![1, "B"]]))]);
    data(&table.join("sub/More.xlsx"), vec![("Items#more", sheet(row!["Id", "Kind"], vec![row![2, "A"]]))]);
    let out = tmp.join("out");
    let result = build(&table, &out, &["--schema", &s(&table.join("Schema"))]);
    assert_eq!(result.code, 0, "{}", result.stderr);
    assert!(read(&out.join("cpp/EDrKind.h"))
        .starts_with("// Generated by DrTableSystem. Do not edit. Source: Enums/Kind.enum.xlsx / Kind\n"));
    assert_eq!(ids(&out, "client", "Items"), [1, 2]);
}

