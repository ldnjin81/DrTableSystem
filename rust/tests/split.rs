#[test]
fn data_header_must_match_the_schema() {
    let cases = [
        (row!["Id", "Name", "Cost", "Weight"], "D1", "필드 'Weight'이 스키마 [Items.schema.xlsx]Items에 없습니다"),
        (row!["Id", "Name"], "A1", "필드 'Cost'의 열이 없습니다 (스키마 [Items.schema.xlsx]Items!A4)"),
        (row!["Id", "Name", "Cost", "Name"], "D1", "필드명 'Name'이 중복되었습니다"),
    ];
    for (header, cell, message) in cases {
        let tmp = Tmp::new();
        schema(&tmp, "Items", &FIELDS);
        data(&tmp.join("Items.xlsx"), vec![("Items", sheet(header, vec![row![1, "Sword", 10, 1]]))]);
        let out = tmp.join("out");
        let result = build(&tmp, &out, &[]);
        assert_eq!(result.code, 1, "{message}");
        assert!(result.stderr.contains(&format!("[Items.xlsx]Items!{cell}: {message}")), "{}", result.stderr);
        assert!(!out.exists());
    }
}

