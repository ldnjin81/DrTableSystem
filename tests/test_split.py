def test_hidden_folders_and_lock_files_are_skipped(tmp_path: Path) -> None:
    _schema(tmp_path, "Items", FIELDS)
    _data(tmp_path / "Items.xlsx", {"Items": [NAMES, *VIEW, [1, "Sword", 10]]})
