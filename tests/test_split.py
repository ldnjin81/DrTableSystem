"""같은 이름의 시트를 여러 파일에 두어 한 테이블로 합치는 기능과 [파일]시트 위치 표기 테스트."""

from __future__ import annotations

import json
from pathlib import Path

import pytest
from openpyxl import Workbook

from tablegen.cli import main

HEAD = [["Id", "Name", "Cost"], ["ID<int32>", "name", "int32"], ["all", "all", "server"]]


def _save(path: Path, sheets: dict[str, list[list[object]]]) -> None:
    workbook = Workbook()
    workbook.remove(workbook.active)
    for name, rows in sheets.items():
        sheet = workbook.create_sheet(name)
        for record in rows:
            sheet.append(record)
    path.parent.mkdir(parents=True, exist_ok=True)
    workbook.save(path)


def _build(source: Path, root: Path, *extra: str) -> int:
    return main(["build", "--input", str(source), "--out-cpp", str(root / "cpp"),
                 "--out-client", str(root / "client"), "--out-server", str(root / "server"), *extra])


def _rows(root: Path, scope: str, table: str) -> list[dict]:
    return json.loads((root / scope / f"{table}.json").read_text(encoding="utf-8"))["rows"]


def test_same_sheet_name_in_several_files_is_one_table(tmp_path: Path) -> None:
    data = tmp_path / "data"
    _save(data / "Items_Weapons.xlsx", {"Items": [*HEAD, [1, "Sword", 10]]})
    _save(data / "Items_Armor.xlsx", {"Items": [*HEAD, [20, "Mail", 30]]})
    # 하위 폴더의 파일도 합쳐지고, 열 순서는 달라도 된다.
    _save(data / "event" / "Summer.xlsx", {"Items": [
        ["Cost", "Id", "Name"], ["int32", "ID<int32>", "name"], ["server", "all", "all"], [5, 3, "Fan"]]})
    assert _build(data, tmp_path / "out") == 0
    rows = _rows(tmp_path / "out", "server", "Items")
    assert [(row["Id"], row["Name"], row["Cost"]) for row in rows] == [
        (1, "Sword", 10), (3, "Fan", 5), (20, "Mail", 30)]
    assert list(rows[1]) == ["Id", "Name", "Cost"]
    header = (tmp_path / "out" / "cpp" / "DtItemsRow.h").read_text(encoding="utf-8")
    assert header.startswith(
        "// Generated by ue-tablegen. Do not edit. Sources:\n"
        "//   Items_Armor.xlsx / Items\n"
        "//   Items_Weapons.xlsx / Items\n"
        "//   event/Summer.xlsx / Items\n"
        "#pragma once\n")


def test_single_source_comment(tmp_path: Path) -> None:
    _save(tmp_path / "Items.xlsx", {"Items": [*HEAD, [1, "Sword", 10]]})
    assert _build(tmp_path, tmp_path / "out") == 0
    header = (tmp_path / "out" / "cpp" / "DtItemsRow.h").read_text(encoding="utf-8")
    assert header.startswith("// Generated by ue-tablegen. Do not edit. Source: Items.xlsx / Items\n")


def test_split_table_matches_unsplit_output(tmp_path: Path) -> None:
    _save(tmp_path / "one.xlsx", {"Items": [*HEAD, [1, "Sword", 10], [2, "Axe", 12]]})
    _save(tmp_path / "split" / "a.xlsx", {"Items": [*HEAD, [2, "Axe", 12]]})
    _save(tmp_path / "split" / "b.xlsx", {"Items": [*HEAD, [1, "Sword", 10]]})
    assert _build(tmp_path / "one.xlsx", tmp_path / "o1") == 0
    assert _build(tmp_path / "split", tmp_path / "o2") == 0
    for scope in ("client", "server"):
        assert (tmp_path / "o1" / scope / "Items.json").read_bytes() == \
            (tmp_path / "o2" / scope / "Items.json").read_bytes()


def test_duplicate_key_across_files_names_both_places(
    tmp_path: Path, capsys: pytest.CaptureFixture[str],
) -> None:
    _save(tmp_path / "a.xlsx", {"Items": [*HEAD, [1, "Sword", 10]]})
    _save(tmp_path / "b.xlsx", {"Items": [*HEAD, [1, "Axe", 12]]})
    assert _build(tmp_path, tmp_path / "out") == 1
    error = capsys.readouterr().err
    assert error.startswith("[b.xlsx]Items!A4")
    assert "[a.xlsx]Items!A4" in error


def test_name_case_is_checked_across_files(
    tmp_path: Path, capsys: pytest.CaptureFixture[str],
) -> None:
    head = [["Id"], ["ID<name>"], ["all"]]
    _save(tmp_path / "a.xlsx", {"T": [*head, ["Sword"]]})
    _save(tmp_path / "b.xlsx", {"T": [*head, ["sword"]]})
    assert _build(tmp_path, tmp_path / "out") == 1
    error = capsys.readouterr().err
    assert error.startswith("[b.xlsx]T!A4") and "[a.xlsx]T!A4" in error


@pytest.mark.parametrize(
    ("other", "message"),
    [
        ([["Id", "Name"], ["ID<int32>", "name"], ["all", "all"]], "'Cost'이 없습니다"),
        ([[*HEAD[0], "Extra"], [*HEAD[1], "int32"], [*HEAD[2], "all"]], "'Extra'이"),
        ([HEAD[0], ["ID<int32>", "name", "float"], HEAD[2]], "'Cost'의 타입"),
        ([HEAD[0], HEAD[1], ["all", "all", "all"]], "'Cost'의 타입·범위"),
    ],
)
def test_files_must_declare_the_same_fields(
    tmp_path: Path, capsys: pytest.CaptureFixture[str],
    other: list[list[object]], message: str,
) -> None:
    _save(tmp_path / "a.xlsx", {"Items": [*HEAD, [1, "Sword", 10]]})
    _save(tmp_path / "b.xlsx", {"Items": [*other, [2, "Axe", 12]]})
    assert _build(tmp_path, tmp_path / "out") == 1
    error = capsys.readouterr().err
    assert message in error
    assert error.startswith("[b.xlsx]Items!")
    assert "[a.xlsx]Items" in error


def test_enums_cannot_be_split(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    enum = [["Id"], ["ID<name>"], ["all"], ["A"]]
    _save(tmp_path / "a.xlsx", {"<enum>Kind": enum})
    _save(tmp_path / "b.xlsx", {"<enum>Kind": enum})
    assert _build(tmp_path, tmp_path / "out") == 1
    error = capsys.readouterr().err
    assert error.startswith("[b.xlsx]<enum>Kind!A1") and "[a.xlsx]<enum>Kind" in error


def test_invalid_table_name_names_the_file(
    tmp_path: Path, capsys: pytest.CaptureFixture[str],
) -> None:
    _save(tmp_path / "a.xlsx", {"Items@A": [*HEAD, [1, "Sword", 10]]})
    assert _build(tmp_path, tmp_path / "out") == 1
    assert "[a.xlsx]Items@A!A1" in capsys.readouterr().err


def test_hidden_folders_and_lock_files_are_skipped(tmp_path: Path) -> None:
    _save(tmp_path / "Items.xlsx", {"Items": [*HEAD, [1, "Sword", 10]]})
    _save(tmp_path / ".backup" / "Items.xlsx", {"Items": [*HEAD, [1, "Sword", 10]]})
    assert _build(tmp_path, tmp_path / "out") == 0
